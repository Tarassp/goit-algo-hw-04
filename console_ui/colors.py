"""
ANSI escape-коди для стилізації тексту у терміналі.

Структура escape-коду:
    \\033[Nm  — де N це числовий код стилю/кольору

Діапазони кодів:
    0       — скидання усіх стилів (RESET)
    1       — жирний шрифт (BOLD)
    30-37   — кольори тексту (звичайні)
    40-47   — кольори фону (звичайні)
    90-97   — кольори тексту (яскраві)
    100-107 — кольори фону (яскраві)
"""

RESET = "\033[0m"

BOLD = "\033[1m"

BLACK = "\033[30m"
RED = "\033[31m"
GREEN = "\033[32m"
YELLOW = "\033[33m"
BLUE = "\033[34m"
MAGENTA = "\033[35m"
CYAN = "\033[36m"
WHITE = "\033[97m"

BLACK_BG = "\033[40m"
RED_BG = "\033[41m"
GREEN_BG = "\033[42m"
YELLOW_BG = "\033[43m"
BLUE_BG = "\033[44m"
MAGENTA_BG = "\033[45m"
CYAN_BG = "\033[46m"
WHITE_BG = "\033[47m"
